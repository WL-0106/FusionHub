# -*- coding: utf-8 -*-
"""PK9015F 电压测量模块 寄存器表与工程量换算。

依据：PK9015F 通讯协议说明（见 F:/模型/6aa36ea09cf4429927b10267/PK9015F_通讯协议说明.md），
从 PK9015F上位机控制软件.exe（PyInstaller + Python 3.10）反编译反推。

设备是「交流电压测量模块」，量程 AC 250V，支持 12 / 24 通道切换。

寄存器表（功能码 03H 读 / 06H 写，地址无偏移）：
------------------------------------------------------------
寄存器   内容            属性        换算
0x0000   ADDR          06写       模块地址（1~255），写后需重新上电
0x0001   BPS           06写       波特率代码（03~07H）
0x0002   量程          03读       值 × 100 = 实际量程（250V → 存 25000）
0x0003~  测量值        03读       电压数据（有符号 16 位补码，raw×量程/10000 = V）
0x000F~  修正值        03读/06写  电压修正值（12 个，有符号 16 位补码，值/100 = V）

电压换算（反编译确认）：
    原始数据为有符号 16 位补码（raw > 32767 时 raw -= 65536）；
    电压(V) = raw × 量程 / 10000，显示两位小数。
    量程默认 250V（AC），量程寄存器值 × 100 = 实际量程（寄存器存 25000）。
    修正值：值 / 100（V），写时 修正值×100 转补码。
"""

from __future__ import annotations

# ------------------------------------------------------------ 寄存器地址

REG_ADDR = 0x0000          # 模块地址（1~255）
REG_BPS = 0x0001           # 波特率代码
REG_RANGE = 0x0002         # 量程（值 × 100 = 实际量程）
REG_DATA_START = 0x0003    # 电压测量值起始
REG_CORR_START = 0x000F    # 电压修正值起始（12 个）

CHANNEL_COUNT = 12         # 默认 12 通道（可切换 24 通道）
CHANNEL_COUNT_MAX = 24

CORR_COUNT = 12

# 默认量程（AC 250V）
DEFAULT_RANGE = 250.0

# 波特率码（写寄存器 0x0001）
BAUD_CODES = {1200: 0x03, 2400: 0x04, 4800: 0x05, 9600: 0x06, 19200: 0x07}
BAUD_BY_CODE = {v: k for k, v in BAUD_CODES.items()}

# 换算分母
SCALE = 10000.0


def signed16(raw: int) -> int:
    """16 位补码解码（raw > 32767 时减去 65536）。"""
    raw &= 0xFFFF
    if raw > 0x7FFF:
        return raw - 0x10000
    return raw


def raw_to_voltage(raw: int, range_v: float = DEFAULT_RANGE) -> float:
    """原始值(16 位补码) → 电压(V)。"""
    return signed16(raw) * range_v / SCALE


def raw_to_corr(raw: int) -> float:
    """修正值原始值(16 位补码) → 修正值(V)。"""
    return signed16(raw) / 100.0


def corr_to_raw(v: float) -> int:
    """修正值(V) → 16 位补码原始值。"""
    return int(round(v * 100.0)) & 0xFFFF


