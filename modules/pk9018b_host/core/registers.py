# -*- coding: utf-8 -*-
"""PK9018B-8 热电阻温度采集模块 寄存器表与工程量换算。

依据：PK9018B-8 通讯协议说明（见 F:/模型/6aa36ea09cf4429927b10267/PK9018B-8_通讯协议说明.md）。

设备是「8 通道热电阻（RTD）温度采集模块」，输入通道 CH0~CH7，
支持 PT100 / CU100 / CU50 / PT500 / PT1000 等三线制热电阻。

寄存器表（功能码 03H 读 / 10H 写，地址无偏移）：
------------------------------------------------------------
寄存器   内容            属性        换算
0x0000   ADDR/BPS       03读/10写    高 8 位=模块地址(00~FFH)，低 8 位=波特率码(03~07H)
0x0001~0008  通道0~7 温度修正值  03读/10写  有符号 16 位，BIT15 符号位，值/100 = ℃
0x0009~0010  通道0~7 温度测量值  03读      有符号 16 位，BIT15 符号位，值/100 = ℃

温度换算：
    16 位有符号，BIT15=1 表示负数（取低 15 位取反加 1 得绝对值）；
    实际温度 = 值 / 100（℃），分辨率 0.01℃。
    量程 -50~300℃ 时有符号位；0~650℃ 时无符号。
"""

from __future__ import annotations

# ------------------------------------------------------------ 寄存器地址

REG_ADDR_BPS = 0x0000      # 地址(高 8 位) + 波特率码(低 8 位)
REG_CORR0 = 0x0001         # 通道 0 温度修正值（8 路连续 0x0001~0x0008）
REG_TEMP0 = 0x0009         # 通道 0 温度测量值（8 路连续 0x0009~0x0010）
CHANNEL_COUNT = 8

# 读温度起始地址与数量（一条报文读完全部 8 路测量值）
READ_START = REG_TEMP0
READ_COUNT = CHANNEL_COUNT

# 修正值起始地址与数量
CORR_START = REG_CORR0
CORR_COUNT = CHANNEL_COUNT

# 波特率码（写寄存器 0x0000 低字节）
BAUD_CODES = {1200: 0x03, 2400: 0x04, 4800: 0x05, 9600: 0x06, 19200: 0x07}
BAUD_BY_CODE = {v: k for k, v in BAUD_CODES.items()}

# 温度换算分母（值/100 = ℃，分辨率 0.01℃）
TEMP_SCALE = 100.0


def signed16(raw: int) -> int:
    """16 位符号-绝对值解码：BIT15 为符号位（1=负），低 15 位为绝对值。"""
    raw &= 0xFFFF
    mag = raw & 0x7FFF
    return -mag if (raw & 0x8000) else mag


def raw_to_temp_c(raw: int) -> float:
    """原始值(16 位符号-绝对值) → 温度(℃)。"""
    return signed16(raw) / TEMP_SCALE


def temp_to_raw(c: float) -> int:
    """温度(℃) → 16 位符号-绝对值原始值（写修正值用，负值置 BIT15 + 绝对值）。"""
    v = int(round(c * TEMP_SCALE))
    if v < 0:
        return 0x8000 | ((-v) & 0x7FFF)
    return v & 0x7FFF


